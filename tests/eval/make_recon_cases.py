#!/usr/bin/env python3
"""Build cases.recon.yaml from cases.deep.yaml (dev-only; needs PyYAML).

Recon is easy on a single-flaw snippet, so each recon case is a small "repo": one REAL F40/F41 case
plus up to three FP twins of OTHER classes from the same skill — code that looks suspicious and is
safe. The model must rank the real flaw first. Deterministic: the same input gives the same file.

Usage: python3 tests/eval/make_recon_cases.py   (from the repo root or tests/eval)
"""
import os
import random
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 20261117
DISTRACTORS = 3


def files_of(code):
    return re.findall(r"^# ([\w./-]+\.\w+)", code, re.M)


class Block(str):
    pass


yaml.SafeDumper.add_representer(Block, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def main():
    with open(os.path.join(HERE, "cases.deep.yaml"), encoding="utf-8") as fh:
        cases = yaml.safe_load(fh)
    for c in cases:
        c["files"] = files_of(c["vars"]["code"])
    real = [c for c in cases if c["vars"]["expected"] == "REAL" and c["metadata"]["card"] in ("F40", "F41")]
    fps = [c for c in cases if c["vars"]["expected"] == "FP"]
    rng = random.Random(SEED)
    out = []
    for r in real:
        pool = [f for f in fps if f["vars"]["skill"] == r["vars"]["skill"]
                and f["metadata"]["class"] != r["metadata"]["class"] and not set(f["files"]) & set(r["files"])]
        rng.shuffle(pool)
        chosen, used = [], set(r["files"])
        for f in pool:
            if len(chosen) == DISTRACTORS:
                break
            if set(f["files"]) & used:
                continue
            chosen.append(f)
            used |= set(f["files"])
        parts = [r] + chosen
        rng.shuffle(parts)
        sink_file = r["vars"]["candidate"].split(":", 1)[0]
        assert sink_file in r["files"], sink_file
        out.append({
            "description": f"recon {r['metadata']['card']} {r['metadata']['class']} — {len(chosen)} distractors",
            "vars": {
                "skill": r["vars"]["skill"],
                "code": Block("\n".join(p["vars"]["code"].rstrip("\n") + "\n" for p in parts)),
                "expected_file": sink_file,
            },
            "metadata": {"split": "dev", "card": r["metadata"]["card"], "class": r["metadata"]["class"],
                         "distractors": len(chosen)},
        })
    header = ("# Recon corpus — GENERATED by make_recon_cases.py from cases.deep.yaml; do not edit by hand.\n"
              "# One REAL F40/F41 flaw among FP twins of other classes; scored on where the model ranks it.\n\n")
    with open(os.path.join(HERE, "cases.recon.yaml"), "w", encoding="utf-8") as fh:
        fh.write(header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=1000))
    print(f"wrote {len(out)} recon cases")


if __name__ == "__main__":
    main()
