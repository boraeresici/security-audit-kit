#!/usr/bin/env bash
# scripts/skill-sums.sh — regenerate lib/released-skills.sums: the cksum of every skill template in
# every release tag (RCs included), plus the current templates (the release being prepared).
#
# install.sh removes a skill copy only if it is provably the kit's own: recorded at install,
# identical to this kit's template, or identical to a RELEASED one. The last case is the one this
# file serves. An older kit installed the copy, the template changed since, and without the record
# the copy would look edited and stay. Upgrading from an old pin with an old bootstrap.sh still
# works, because the file ships with the new kit. Run at release prep; release.sh checks it.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.."
out=lib/released-skills.sums
sum(){ cksum | awk '{print $1"-"$2}'; }   # the same form as install.sh's fsum
{
  for t in $(git tag -l 'v*'); do
    git ls-tree -r --name-only "$t" -- skills/ | while IFS= read -r p; do
      case "$p" in
        skills/*.skill.md) n="${p#skills/}"; n="${n%.skill.md}" ;;
        skills/*/SKILL.md) n="${p#skills/}"; n="${n%/SKILL.md}" ;;
        *) continue ;;
      esac
      printf '%s %s\n' "$n" "$(git show "$t:$p" | sum)"
    done
  done
  for f in skills/*/SKILL.md; do n="${f#skills/}"; printf '%s %s\n' "${n%/SKILL.md}" "$(sum < "$f")"; done
} | sort -u > "$out.tmp"
{ echo "# <skill> <cksum-size> of every released template; generated by scripts/skill-sums.sh — do not edit"
  cat "$out.tmp"; } > "$out"
rm -f "$out.tmp"
echo "scripts/skill-sums.sh: $(grep -vc '^#' "$out") template sums -> $out"
